@define(eq=False)
class Sensor(SynapseDevice):
    """Base class for sensors"""

    name: str = field(default="sensor", kw_only=True)
    """name of the sensor device"""
    sigma_noise: float = field(kw_only=True)
    """standard deviation of Gaussian noise in ΔF/F measurement"""
    dFF_1AP: float = field(kw_only=True)
    """ΔF/F for 1 AP, only used for scope SNR cutoff"""
    location: str = field(kw_only=True)
    """where sensor is expressed: cytoplasm or membrane"""

    @location.validator
    def _check_location(self, attribute, value):
        if value not in ("cytoplasm", "membrane"):
            raise ValueError(
                f"indicator location must be 'cytoplasm' or 'membrane', not {value}"
            )

    @property
    def snr(self) -> float:
        """Reference signal-to-noise ratio for one action potential.

        The reference SNR is the single-action-potential fluorescence
        response (dFF_1AP) divided by the standard deviation of
        Gaussian fluorescence noise (sigma_noise):

            SNR_reference = dFF_1AP / sigma_noise

        For light-dependent imaging, the effective noise level can
        change with excitation brightness and neuronal dwell time.

        The light-dependent model uses a Hill function to estimate
        relative fluorescence brightness:

            H(P) = P**2 / (P**2 + P_sat**2)

        where P is laser power and P_sat is the saturation parameter.

        Assuming a circular soma and circular imaging field of view,
        the fraction of scanning time allocated to a neuron is:

            geometric_fraction = (soma_radius / (img_width / 2))**2

        The estimated dwell time is:

            dwell_time = (1 / frequency - flyback_time)
                         * geometric_fraction

        Relative brightness is calculated against reference imaging
        conditions:

            brightness_ratio =
                (H(laser_power) * dwell_time)
                / (H(reference_power) * reference_dwell)

        Under a shot-noise-dominated approximation, the effective
        Gaussian noise standard deviation scales as:

            sigma_scaled = sigma_noise / sqrt(brightness_ratio)

        The expected light-dependent SNR is therefore:

            SNR_effective = dFF_1AP / sigma_scaled

        The relative single-spike response dFF_1AP remains constant
        as excitation brightness changes.

        Notes
        -----
        This property returns the reference SNR only. It does not
        calculate brightness-dependent SNR or modify fluorescence
        traces generated by Scope.

        See Also
        --------
        LightDependentGECI.compute_hill_raster_noise
            Calculate estimated dwell time, brightness-dependent
            Gaussian noise, and effective SNR.
        """
        return self.dFF_1AP / self.sigma_noise

    def get_state(self) -> dict[NeuronGroup, np.ndarray]:
        """Returns a {neuron_group: fluorescence} dict of dFF values."""
        pass

    @property
    def exc_spectrum(self) -> list[tuple[float, float]]:
        """Excitation spectrum, alias for :attr:`spectrum`"""
        return self.spectrum


@define(eq=False)
class CalciumModel:
    """Base class for how GECI computes calcium concentration

    Must provide variable Ca (molar) in model."""

    model: str
    on_pre: str = field(default="", init=False)

@define(eq=False)
class PreexistingCalcium(CalciumModel):
    """Calcium concentration is pre-existing in neuron model"""

    model: str = field(default="Ca = Ca_pre : mmolar", init=False)


@define(eq=False)
class DynamicCalcium(CalciumModel):
    """Simulates intracellular calcium dynamics from spikes."""

    on_pre: str = field(default="Ca += dCa_T / (1 + kappa_S + kappa_B)", init=False)
    model: str = field(
        default="""
            dCa/dt = -gamma * (Ca - Ca_rest) / (1 + kappa_S + kappa_B) : mmolar (clock-driven)
            kappa_B = B_T * K_d / (Ca + K_d)**2 : 1""",
        init=False,
    )

    Ca_rest: Quantity = field(default=50 * nmolar, kw_only=True)
    gamma: Quantity = field(default=292.3 / second, kw_only=True)
    B_T: Quantity = field(default=200 * umolar, kw_only=True)
    kappa_S: float = field(default=110.0, kw_only=True)
    dCa_T: Quantity = field(default=7.6 * umolar, kw_only=True)

    def init_syn_vars(self, syn: Synapses) -> None:
        syn.Ca = self.Ca_rest


@define(eq=False)
class CalBindingActivationModel:
    """Base class for modeling calcium binding/activation"""
    model: str


@define(eq=False)
class NullBindingActivation(CalBindingActivationModel):
    """Doesn't model binding/activation; goes straight from [Ca2+] to ΔF/F"""
    model: str = field(default="CaB_active = Ca: mmolar", init=False)


@define(eq=False)
class DoubExpCalBindingActivation(CalBindingActivationModel):
    """Double exponential kernel convolution representing CaB binding/activation."""

    model: str = field(
        default="""
            CaB_active = Ca_rest + b : mmolar  # add tiny bit to avoid /0
            db/dt = beta : mmolar (clock-driven)
            lam = 1/tau_off + 1/tau_on : 1/second
            kap = 1/tau_off : 1/second
            dbeta/dt = (                    # should be M/s/s
                A * (lam - kap) * (Ca - Ca_rest)  # M/s/s
                - (kap + lam) * beta        # M/s/s
                - kap * lam * b    # M/s/s
            ) : mmolar/second (clock-driven)
            """,
        init=False,
    )

    A: float = field(kw_only=True)
    tau_on: Quantity = field(kw_only=True)
    tau_off: Quantity = field(kw_only=True)
    Ca_rest: Quantity = field(kw_only=True)

    def init_syn_vars(self, syn: Synapses) -> None:
        syn.b = 0
        syn.beta = 0


@define(eq=False)
class ExcitationModel:
    model: str = field(default="exc_factor = 1 : 1", init=False)

@define(eq=False)
class NullExcitation(ExcitationModel):
    model: str = field(default="exc_factor = 1 : 1", init=False)


@define(eq=False)
class LightExcitation(ExcitationModel):
    model: str = field(default="""
    exc_factor = baseline + ((A * ((Irr * (soma_radius / img_width)**2 * pi * (mwatt))**n)/(ec50**n + (Irr_pre * (soma_radius / img_width)**2 * pi * (1000/watt))**n))
                * exp(-k * Irr * (soma_radius / img_width)**2 * pi * (mwatt)) * (1/Hz)) : 1
    """, init=False)

    baseline: float = field(default=1.0, kw_only=True)
    A: float = field(default=1.0, kw_only=True)
    n: float = field(default=1.0, kw_only=True)
    ec50: float = field(default=1.0, kw_only=True)
    k: float = field(default=0.0, kw_only=True)
    img_width: float = field(default=500.0, kw_only=True)


@define(eq=False)
class GECI(Sensor):
    name: str = field(default="GECI", kw_only=True)
    cal_model: CalciumModel = field(kw_only=True)
    bind_act_model: CalBindingActivationModel = field(kw_only=True)
    exc_model: ExcitationModel = field(kw_only=True)

    K_d: Quantity = field(kw_only=True)
    n_H: float = field(kw_only=True)
    dFF_max: float = field(kw_only=True)

    location: str = field(default="cytoplasm", init=False)
    fluor_model: str = field(
        default="""
        dFF_baseline = 1/(1 + (K_d / Ca_rest)**n_H) : 1
        dFF = exc_factor * rho_rel * dFF_max * (
        1/ (1 + (K_d / CaB_active) ** n_H) - dFF_baseline) : 1
        rho_rel : 1
    """, init=False
    )

    def get_state(self) -> dict[NeuronGroup, np.ndarray]:
        return {ng_name: syn.dFF for ng_name, syn in self.synapses.items()}

    def __attrs_post_init__(self):
        self.model = "\n".join(
            [
                self.cal_model.model,
                self.bind_act_model.model,
                self.exc_model.model,
                self.fluor_model,
            ]
        )
        self.on_pre = self.cal_model.on_pre

    def init_syn_vars(self, syn: Synapses) -> None:
        for model in [self.cal_model, self.bind_act_model, self.exc_model]:
            if hasattr(model, "init_syn_vars"):
                model.init_syn_vars(syn)

    @property
    def params(self) -> dict:
        params = asdict(self, recurse=False)
        for f in fields_dict(Sensor):
            params.pop(f)
        for f in fields_dict(LightDependent):
            params.pop(f, None)
        for key in list(params.keys()):
            if key.startswith("_"):
                params.pop(key)
        for model in [self.cal_model, self.bind_act_model, self.exc_model]:
            to_add = asdict(model, recurse=False)
            to_add.pop("model")
            params.update(to_add)
        return params


@define(eq=False, slots=False)
class LightDependentGECI(GECI, LightDependent):
    name: str = field(default="LightDependentGECI", kw_only=True)

    def __attrs_post_init__(self):
        super().__attrs_post_init__()
        if hasattr(LightDependent, "__post_init__"):
            LightDependent.__post_init__(self)


    def compute_hill_raster_noise(
        self,
        laser_power: float,
        frequency: float,
        soma_radius: float,
        img_width: float,
        flyback_time: float,
        *,
        reference_power: float,
        reference_dwell: float,
        i_sat: float = 10.0,
    ) -> tuple[float, float, float]:
        """Estimate brightness-dependent noise and SNR for raster imaging.

        This method estimates the time spent imaging a neuron, then
        uses laser-dependent fluorescence brightness to scale the
        sensor's reference Gaussian noise standard deviation.

        Parameters
        ----------
        laser_power : float
            Excitation laser power. Increasing power increases expected
            SNR until the Hill response approaches saturation.
        frequency : float
            Imaging frequency in frames per second (Hz). Increasing
            frequency reduces the available dwell time per frame and
            therefore decreases expected SNR, all else being equal.
        soma_radius : float
            Radius of the neuronal soma. A larger soma occupies more
            of the imaging field and receives more estimated dwell time.
        img_width : float
            Diameter of the circular imaging field. Increasing this
            width decreases the fraction of scanning time allocated
            to an individual soma.
        flyback_time : float
            Time in seconds per frame unavailable for imaging.
        reference_power : float
            Laser power at which the reference noise level was calibrated.
        reference_dwell : float
            Neuronal dwell time in seconds at the reference condition.
        i_sat : float, optional
            Saturation parameter for the Hill brightness response.
            Defaults to 10.0, in the same power units as laser_power.

        Returns
        -------
        noisy_signal : float
            Single-spike dF/F response with sampled Gaussian noise.
        t_dwell : float
            Estimated dwell time allocated to the neuron, in seconds.
        snr : float
            Expected single-spike SNR under the specified conditions.

        Notes
        -----
        The dwell-time estimate assumes a circular soma and circular
        imaging field. It does not simulate individual raster lines
        or laser pulses.

        The calculation scales sigma_noise using the ratio of
        excitation brightness times dwell time relative to reference
        conditions. The relative spike response dFF_1AP is unchanged.

        This is a standalone estimate and does not currently modify
        the fluorescence traces generated by Scope.

        See Also
        --------
        Sensor.snr
            Reference SNR and detailed brightness-dependent SNR
            methodology.
        """
        if frequency <= 0 or laser_power <= 0 or reference_power <= 0:
            raise ValueError("Frequency and laser powers must be positive.")
        if i_sat <= 0 or reference_dwell <= 0:
            raise ValueError("Saturation power and reference dwell must be positive.")
        if soma_radius <= 0 or img_width <= 0 or flyback_time < 0:
            raise ValueError("Invalid geometry or flyback time.")

        active_frame_time = 1.0 / frequency - flyback_time
        if active_frame_time <= 0:
            raise ValueError("Flyback time must be shorter than frame period.")

        # Circular soma relative to circular field of view.
        geometric_fraction = (soma_radius / (img_width / 2.0)) ** 2
        if geometric_fraction > 1:
            raise ValueError("Soma cannot exceed the imaging field of view.")

        t_dwell = active_frame_time * geometric_fraction

        hill_factor = laser_power**2 / (laser_power**2 + i_sat**2)
        reference_hill = reference_power**2 / (reference_power**2 + i_sat**2)

        brightness_ratio = (hill_factor * t_dwell) / (
            reference_hill * reference_dwell
        )
        sigma_scaled = self.sigma_noise / np.sqrt(brightness_ratio)

        snr = self.dFF_1AP / sigma_scaled
        noisy_signal = self.dFF_1AP + np.random.normal(0, sigma_scaled)

        return noisy_signal, t_dwell, snr


def geci(
    light_dependent: bool, doub_exp_conv: bool, pre_existing_cal: bool, **kwparams
) -> GECI:
    ExcModel = LightExcitation if light_dependent else NullExcitation
    CalModel = PreexistingCalcium if pre_existing_cal else DynamicCalcium
    BAModel = DoubExpCalBindingActivation if doub_exp_conv else NullBindingActivation

    def init_from_kwparams(cls, **more_kwargs):
        kwparams.update(more_kwargs)
        kwparams_to_keep = {}
        for field_name, field in fields_dict(cls).items():
            if field.init and field_name in kwparams:
                kwparams_to_keep[field_name] = kwparams[field_name]
        return cls(**kwparams_to_keep)

    GECIClass = LightDependentGECI if light_dependent else GECI

    return init_from_kwparams(
        GECIClass,
        cal_model=init_from_kwparams(CalModel),
        exc_model=init_from_kwparams(ExcModel),
        bind_act_model=init_from_kwparams(BAModel),
        **kwparams,
    )


def _create_geci_fn(
    name,
    K_d,
    n_H,
    dFF_max,
    sigma_noise_rel,
    dFF_1AP_rel=None,
    ca_amp=None,
    t_on=None,
    t_off=None,
    extra_doc="",
    **extra_kwparams
):
    gcamp6s_dFF_1AP_dana2019 = 0.133
    gcamp6s_snr_1AP_dana2019 = 4.4
    sigma_gcamp6s = gcamp6s_dFF_1AP_dana2019 / gcamp6s_snr_1AP_dana2019
    sigma_noise = sigma_noise_rel * sigma_gcamp6s
    dFF_1AP = (dFF_1AP_rel * gcamp6s_dFF_1AP_dana2019) if dFF_1AP_rel is not None else None

    spectrum = extra_kwparams.pop('spectrum', [(488 * nmeter, 1.0)])

    def geci_fn(
        light_dependent=False,
        doub_exp_conv=True,
        pre_existing_cal=False,
        K_d=K_d * nmolar,
        n_H=n_H,
        dFF_max=dFF_max,
        sigma_noise=sigma_noise,
        dFF_1AP=dFF_1AP,
        ca_amp=ca_amp,
        t_on=t_on,
        t_off=t_off,
        Ca_rest=50 * nmolar,
        kappa_S=110,
        gamma=292.3 / second,
        B_T=200 * umolar,
        dCa_T=7.6 * umolar,
        name=name,
        spectrum=spectrum,
        img_width=500.0,
        **fn_kwargs,
    ) -> GECI:
        A = ca_amp / (second / 100) if ca_amp else None
        tau_on = second / t_on if t_on else None
        tau_off = second / t_off if t_off else None

        merged_kwargs = {**extra_kwparams, **fn_kwargs}

        return geci(
            light_dependent,
            doub_exp_conv,
            pre_existing_cal,
            baseline=1.0,
            n=1.0,
            ec50=1.0,
            k=0.0,
            K_d=K_d,
            n_H=n_H,
            dFF_max=dFF_max,
            sigma_noise=sigma_noise,
            dFF_1AP=dFF_1AP,
            Ca_rest=Ca_rest,
            A=A,
            tau_on=tau_on,
            tau_off=tau_off,
            kappa_S=kappa_S,
            gamma=gamma,
            B_T=B_T,
            dCa_T=dCa_T,
            name=name,
            spectrum=spectrum,
            img_width=img_width,
            **merged_kwargs,
        )

    geci_fn.__doc__ = (geci_fn.__doc__ or "") + "\n\n" + (" " * 8) + (extra_doc or "")
    globals()[brian_safe_name(name.lower())] = geci_fn


# Auto-load sensors from CSV if present
target_file = Path(__file__).parent / "gecis.csv"
if target_file.exists():
    try:
        df = pd.read_csv(target_file)
        for index, row in df.iterrows():
            params = row.iloc[6:].dropna().to_dict()
            if "spectrum" in params and isinstance(params["spectrum"], str):
                params["spectrum"] = ast.literal_eval(params["spectrum"])
                spec_list = params["spectrum"]
                params["spectrum"] = [(w * nmeter, s) for (w, s) in spec_list]
            _create_geci_fn(row.iloc[0], **params)
    except Exception as e:
        print(f"Failed to register sensors from csv: {e}")


def load_geci_dataframe(name: str):
    target_file = Path(__file__).parent / "gecis.csv"
    try:
        df = pd.read_csv(target_file)
        mask = df.iloc[:, 0].str.lower() == name.lower()
        if not mask.any():
            return None
        else:
            row = df[df.iloc[:, 0].str.lower() == name.lower()].iloc[0]
            params = row.iloc[6:].dropna().to_dict()
            if "spectrum" in params and isinstance(params["spectrum"], str):
                params["spectrum"] = ast.literal_eval(params["spectrum"])
                spec_list = params["spectrum"]
                params["spectrum"] = [(float(w), s) for (w, s) in spec_list]
            _create_geci_fn(row.iloc[0], **params)
            sensor_name = brian_safe_name(row.iloc[0].lower())
            gcamp_func = globals()[sensor_name]
            gcamp = gcamp_func(light_dependent=True)
            return gcamp
    except Exception as e:
        print(f"Failed to register sensors from csv: {e}")


def Plot_Generator(time_history, dFF_history, count):
    for i in range(dFF_history.shape[1]):
        plt.plot(time_history, dFF_history[:, i], label=f"Neuron Group {i + 1}")
    plt.xlabel('Time in (ms)')
    plt.ylabel('dFF')
    plt.title('dFF over time for different neurons')
    plt.legend()
    plt.savefig(f"dFF_history_over_time_{count}.png")
    plt.show()
